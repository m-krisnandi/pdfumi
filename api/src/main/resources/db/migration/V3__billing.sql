-- Billing: accounts, API keys, usage counters (H2 + PostgreSQL compatible)
CREATE TABLE account (
    id                      UUID PRIMARY KEY,
    email                   VARCHAR(320) NOT NULL,
    plan                    VARCHAR(32)  NOT NULL DEFAULT 'FREE',
    stripe_customer_id      VARCHAR(128),
    stripe_subscription_id  VARCHAR(128),
    subscription_status     VARCHAR(32),
    current_period_end      TIMESTAMP WITH TIME ZONE,
    created_at              TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at              TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE UNIQUE INDEX uq_account_email ON account (email);
CREATE INDEX idx_account_stripe_customer ON account (stripe_customer_id);

CREATE TABLE api_key (
    id          UUID PRIMARY KEY,
    account_id  UUID         NOT NULL,
    key_prefix  VARCHAR(24)  NOT NULL,
    key_hash    VARCHAR(128) NOT NULL,
    label       VARCHAR(128),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at  TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_api_key_account FOREIGN KEY (account_id) REFERENCES account (id)
);

CREATE UNIQUE INDEX uq_api_key_hash ON api_key (key_hash);
CREATE INDEX idx_api_key_account ON api_key (account_id);

CREATE TABLE usage_counter (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quota_key    VARCHAR(160) NOT NULL,
    period_type  VARCHAR(16)  NOT NULL,
    period_key   VARCHAR(32)  NOT NULL,
    tool         VARCHAR(64)  NOT NULL,
    used_count   INT          NOT NULL DEFAULT 0,
    CONSTRAINT uq_usage_counter UNIQUE (quota_key, period_type, period_key, tool)
);

CREATE INDEX idx_usage_counter_lookup ON usage_counter (quota_key, period_type, period_key);
