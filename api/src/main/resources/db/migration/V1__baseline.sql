-- Baseline schema for Pdfumi (H2 + PostgreSQL compatible)
CREATE TABLE usage_event (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tool            VARCHAR(64)  NOT NULL,
    client_key_hash VARCHAR(128) NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_usage_event_tool_created ON usage_event (tool, created_at);

CREATE TABLE api_audit_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id   VARCHAR(64),
    method       VARCHAR(16)  NOT NULL,
    path         VARCHAR(512) NOT NULL,
    status_code  INT          NOT NULL,
    duration_ms  BIGINT       NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_api_audit_created ON api_audit_log (created_at);